    @Test
    void accountAuthorizationDoesNotPermitAccessToAnotherUsersAccount() {
        User caller = createUser("caller@example.com", Role.ACCOUNT_HOLDER);
        User otherUser = createUser("other@example.com", Role.ACCOUNT_HOLDER);
        insertAccount(77L, 0L);
        jdbcTemplate.update(
                "INSERT INTO account_permissions (account_id, user_id, permission) VALUES (?, ?, ?)",
                77L, otherUser.getId(), "OWNER");
        var callerAuthentication = UsernamePasswordAuthenticationToken.authenticated(
                caller.getId().toString(), null, List.of());

        assertFalse(accountAuthorizationService.canViewAccount(callerAuthentication, 77L));
        assertThrows(AccessDeniedException.class,
                () -> accountAuthorizationService.requireViewAccount(callerAuthentication, 77L));
    }

