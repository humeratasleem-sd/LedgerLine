    @Test
    void adminCanChangeAccountPermissionAndTheChangeIsAudited() throws Exception {
        String adminToken = loginToken(Role.ADMIN);
        User accountHolder = createUser("owner@example.com", Role.ACCOUNT_HOLDER);
        insertAccount(88L, 0L);
        jdbcTemplate.update(
                "INSERT INTO account_permissions (account_id, user_id, permission) VALUES (?, ?, 'OWNER')",
                88L, accountHolder.getId());

        mockMvc.perform(put("/api/admin/accounts/88/permissions")
                        .header("Authorization", "Bearer " + adminToken)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("""
                                {"userId":%d,"permission":"VIEW"}
                                """.formatted(accountHolder.getId())))
                .andExpect(status().isNoContent());

        assertEquals("VIEW", jdbcTemplate.queryForObject(
                "SELECT permission FROM account_permissions WHERE account_id = ? AND user_id = ?",
                String.class,
                88L,
                accountHolder.getId()));
        assertEquals(1, jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM audit_events WHERE action = 'ACCOUNT_PERMISSION_CHANGED'",
                Integer.class));
    }

    @Test
    void adminCanDisableRegularUsersAndTheChangeIsAudited() throws Exception {
        String adminToken = loginToken(Role.ADMIN);
        User accountHolder = createUser("member@example.com", Role.ACCOUNT_HOLDER);

        mockMvc.perform(patch("/api/admin/users/{userId}/status", accountHolder.getId())
                        .header("Authorization", "Bearer " + adminToken)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"accountStatus\":\"DISABLED\"}"))
                .andExpect(status().isNoContent());

        assertEquals(AccountStatus.DISABLED,
                userRepository.findById(accountHolder.getId()).orElseThrow().getAccountStatus());
        assertFalse(jdbcTemplate.queryForObject(
                "SELECT active FROM users WHERE id = ?", Boolean.class, accountHolder.getId()));
        assertEquals(1, jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM audit_events WHERE action = 'USER_STATUS_CHANGED'",
                Integer.class));
    }

