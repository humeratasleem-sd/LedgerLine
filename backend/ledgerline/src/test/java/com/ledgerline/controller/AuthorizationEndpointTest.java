    @Test
    void expiredAndInvalidTokensAreRejected() throws Exception {
        User user = createUser("person@example.com", Role.ACCOUNT_HOLDER);
        Instant now = Instant.now();
        String expired = jwtEncoder.encode(JwtEncoderParameters.from(
                JwsHeader.with(MacAlgorithm.HS256).build(),
                JwtClaimsSet.builder()
                        .issuer("ledgerline")
                        .subject(user.getId().toString())
                        .issuedAt(now.minusSeconds(120))
                        .expiresAt(now.minusSeconds(60))
                        .claim("roles", List.of("ACCOUNT_HOLDER"))
                        .build())).getTokenValue();

        mockMvc.perform(get("/api/auth/me").header("Authorization", "Bearer " + expired))
                .andExpect(status().isUnauthorized());
        mockMvc.perform(get("/api/auth/me").header("Authorization", "Bearer not-a-jwt"))
                .andExpect(status().isUnauthorized());
    }

