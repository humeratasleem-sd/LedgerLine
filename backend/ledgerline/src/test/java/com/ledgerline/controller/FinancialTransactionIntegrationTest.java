    @Test
    void concurrentWithdrawalsCannotSpendTheSameBalanceTwice() throws Exception {
        User admin = createUser("admin@example.com", Role.ADMIN);
        insertAccount(50L, "ACCOUNT-50", 5_000L);
        String token = token(admin);
        String body = """
                {"sourceAccountId":50,"amountPaise":4000,
                 "externalReference":"settlement-50","externalSettlementVerified":true}
                """;
        CountDownLatch start = new CountDownLatch(1);
        try (ExecutorService executor = Executors.newFixedThreadPool(2)) {
            Future<Integer> first = executor.submit(() -> withdrawalStatus(
                    start, token, "withdraw-key-001", body));
            Future<Integer> second = executor.submit(() -> withdrawalStatus(
                    start, token, "withdraw-key-002", body));
            start.countDown();
            List<Integer> statuses = List.of(first.get(), second.get());
            assertEquals(1, statuses.stream().filter(value -> value == 200).count());
            assertEquals(1, statuses.stream().filter(value -> value == 422).count());
        }

        assertEquals(1_000L, balance(50L));
        assertEquals(2, count("SELECT COUNT(*) FROM transactions"));
        assertEquals(2, count("SELECT COUNT(*) FROM ledger_entries"));
        assertEquals(1, count("SELECT COUNT(*) FROM transactions WHERE status = 'COMPLETED'"));
        assertEquals(1, count("SELECT COUNT(*) FROM transactions WHERE status = 'FAILED'"));
    }

