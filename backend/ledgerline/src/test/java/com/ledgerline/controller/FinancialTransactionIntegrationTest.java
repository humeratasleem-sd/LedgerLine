    @Test
    void adminAttestedDepositCreatesBalancedSystemCounterEntry() throws Exception {
        User admin = createUser("posting-admin@example.com", Role.ADMIN);
        insertAccount(70L, "ACCOUNT-70", 0L);
        insertAccount(71L, "ACCOUNT-71", 0L);

        mockMvc.perform(post("/api/admin/transactions/deposits")
                        .header("Authorization", "Bearer " + token(admin))
                        .header("Idempotency-Key", "deposit-key-001")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("""
                                {"destinationAccountId":70,"amountPaise":2500,
                                 "externalReference":"bank-settlement-70",
                                 "externalSettlementVerified":true}
                                """))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.transactionType").value("DEPOSIT"))
                .andExpect(jsonPath("$.externalReference").value("bank-settlement-70"));

        assertEquals(2_500L, balance(70L));
        assertEquals(2, count("SELECT COUNT(*) FROM ledger_entries"));
        assertEquals(1, count("""
                SELECT COUNT(*) FROM ledger_entries
                WHERE system_account_id IS NOT NULL AND entry_type = 'DEBIT'
                """));
        assertEquals(1, count("SELECT COUNT(*) FROM audit_events WHERE action = 'TRANSACTION_COMPLETED'"));

        mockMvc.perform(post("/api/admin/transactions/deposits")
                        .header("Authorization", "Bearer " + token(admin))
                        .header("Idempotency-Key", "deposit-key-002")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("""
                                {"destinationAccountId":71,"amountPaise":2500,
                                 "externalReference":"bank-settlement-70",
                                 "externalSettlementVerified":true}
                                """))
                .andExpect(status().isConflict());
        assertEquals(0L, balance(71L));
        assertEquals(1, count("SELECT COUNT(*) FROM external_settlements"));
    }

    @Test
    void adminCanListAndFreezeAccountsButCannotCloseAnAccountWithFunds() throws Exception {
        User admin = createUser("account-admin@example.com", Role.ADMIN);
        insertAccount(80L, "ACCOUNT-80", 10L);
        String token = token(admin);

        mockMvc.perform(get("/api/admin/accounts")
                        .header("Authorization", "Bearer " + token))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$[0].balancePaise").value("10"));

        mockMvc.perform(org.springframework.test.web.servlet.request.MockMvcRequestBuilders.patch(
                        "/api/admin/accounts/80/status")
                        .header("Authorization", "Bearer " + token)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"status\":\"CLOSED\"}"))
                .andExpect(status().isConflict());

        mockMvc.perform(org.springframework.test.web.servlet.request.MockMvcRequestBuilders.patch(
                        "/api/admin/accounts/80/status")
                        .header("Authorization", "Bearer " + token)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"status\":\"FROZEN\"}"))
                .andExpect(status().isNoContent());
        assertEquals("FROZEN", jdbcTemplate.queryForObject(
                "SELECT status FROM accounts WHERE id = 80", String.class));
        assertEquals(1, count("SELECT COUNT(*) FROM audit_events WHERE action = 'ACCOUNT_STATUS_CHANGED'"));
    }

    private int withdrawalStatus(CountDownLatch start, String token, String key, String body) throws Exception {
        start.await();
        return mockMvc.perform(post("/api/admin/transactions/withdrawals")
                        .header("Authorization", "Bearer " + token)
                        .header("Idempotency-Key", key)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(body))
                .andReturn()
                .getResponse()
                .getStatus();
    }

    private void createAuditTable() {
        jdbcTemplate.execute("""
                CREATE TABLE audit_events (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    actor_user_id BIGINT,
                    action VARCHAR(100) NOT NULL,
                    entity_type VARCHAR(64) NOT NULL,
                    entity_id VARCHAR(128),
                    request_id VARCHAR(128),
                    details VARCHAR(2000),
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
    }

    private User createUser(String email, Role role) {
        return userRepository.saveAndFlush(new User(
                "LedgerLine Test User",
                email,
                passwordEncoder.encode("test-password-123"),
                role,
                AccountStatus.ACTIVE));
    }

    private String token(User user) {
        Instant issuedAt = Instant.now();
        return jwtEncoder.encode(JwtEncoderParameters.from(
                JwsHeader.with(MacAlgorithm.HS256).build(),
                JwtClaimsSet.builder()
                        .issuer("ledgerline")
                        .subject(user.getId().toString())
                        .issuedAt(issuedAt)
                        .expiresAt(issuedAt.plusSeconds(300))
                        .claim("roles", List.of(user.getRole().name()))
                        .build()))
                .getTokenValue();
    }

    private void insertAccount(long id, String accountNumber, long balancePaise) {
        jdbcTemplate.update("""
                INSERT INTO accounts (id, account_number, currency, balance_paise, status)
                VALUES (?, ?, 'INR', ?, 'ACTIVE')
                """, id, accountNumber, balancePaise);
    }

    private void grant(long accountId, User user, String permission) {
        jdbcTemplate.update("""
                INSERT INTO account_permissions (account_id, user_id, permission)
                VALUES (?, ?, ?)
                """, accountId, user.getId(), permission);
    }

    private long balance(long accountId) {
        return jdbcTemplate.queryForObject(
                "SELECT balance_paise FROM accounts WHERE id = ?", Long.class, accountId);
    }

    private int count(String sql) {
        return jdbcTemplate.queryForObject(sql, Integer.class);
    }

    private long scalarLong(String sql, long parameter) {
        return jdbcTemplate.queryForObject(sql, Long.class, parameter);
    }
