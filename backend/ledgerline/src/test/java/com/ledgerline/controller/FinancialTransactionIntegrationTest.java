    @Test
    void transferIsBalancedAndSameIdempotencyKeyCannotPostTwice() throws Exception {
        User holder = createUser("holder@example.com", Role.ACCOUNT_HOLDER);
        String token = token(holder);
        insertAccount(10L, "ACCOUNT-10", 5_000L);
        insertAccount(11L, "ACCOUNT-11", 100L);
        grant(10L, holder, "TRANSFER");

        String body = """
                {"sourceAccountId":10,"destinationAccountId":11,"amountPaise":2000}
                """;
        MvcResult first = mockMvc.perform(post("/api/transactions/transfers")
                        .header("Authorization", "Bearer " + token)
                        .header("Idempotency-Key", "transfer-key-001")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(body))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.transactionType").value("TRANSFER"))
                .andExpect(jsonPath("$.status").value("COMPLETED"))
                .andReturn();
        String transactionId = com.jayway.jsonpath.JsonPath.read(
                first.getResponse().getContentAsString(), "$.id").toString();

        mockMvc.perform(post("/api/transactions/transfers")
                        .header("Authorization", "Bearer " + token)
                        .header("Idempotency-Key", "transfer-key-001")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(body))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.id").value(Long.parseLong(transactionId)));

        mockMvc.perform(post("/api/transactions/transfers")
                        .header("Authorization", "Bearer " + token)
                        .header("Idempotency-Key", "transfer-key-001")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("""
                                {"sourceAccountId":10,"destinationAccountId":11,"amountPaise":1000}
                                """))
                .andExpect(status().isConflict());

        assertEquals(3_000L, balance(10L));
        assertEquals(2_100L, balance(11L));
        assertEquals(1, count("SELECT COUNT(*) FROM transactions"));
        assertEquals(2, count("SELECT COUNT(*) FROM ledger_entries"));
        assertEquals(2_000L, scalarLong("""
                SELECT SUM(amount_paise) FROM ledger_entries
                WHERE transaction_id = ? AND entry_type = 'DEBIT'
                """, Long.parseLong(transactionId)));
        assertEquals(2_000L, scalarLong("""
                SELECT SUM(amount_paise) FROM ledger_entries
                WHERE transaction_id = ? AND entry_type = 'CREDIT'
                """, Long.parseLong(transactionId)));
    }

    @Test
    void insufficientFundsAreRecordedWithoutChangingTheBalance() throws Exception {
        User holder = createUser("poor@example.com", Role.ACCOUNT_HOLDER);
        insertAccount(20L, "ACCOUNT-20", 500L);
        insertAccount(21L, "ACCOUNT-21", 0L);
        grant(20L, holder, "TRANSFER");

        mockMvc.perform(post("/api/transactions/transfers")
                        .header("Authorization", "Bearer " + token(holder))
                        .header("Idempotency-Key", "refused-key-001")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("""
                                {"sourceAccountId":20,"destinationAccountId":21,"amountPaise":600}
                                """))
                .andExpect(status().isUnprocessableEntity())
                .andExpect(jsonPath("$.status").value("FAILED"))
                .andExpect(jsonPath("$.failureCode").value("INSUFFICIENT_FUNDS"));

        assertEquals(500L, balance(20L));
        assertEquals(0L, balance(21L));
        assertEquals(1, count("SELECT COUNT(*) FROM transactions WHERE status = 'FAILED'"));
        assertEquals(0, count("SELECT COUNT(*) FROM ledger_entries"));
        assertEquals(1, count("SELECT COUNT(*) FROM audit_events WHERE action = 'TRANSACTION_REFUSED'"));
    }

